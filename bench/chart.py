#!/usr/bin/env python3
"""chart.py [patched_verdicts.json]: results/the-ten.svg — per problem, our stress harness
(solved or not, cost, calls) beside the authors' 27B harness and Fable 5 alone (passes of
five), from results/harness-stress-27b.tsv and the authors' verdict file. No dependencies."""
import csv, json, os, sys
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
rows = list(csv.DictReader(open(os.path.join(root, "results", "harness-stress-27b.tsv")), delimiter="\t"))
authors = {}
if len(sys.argv) > 1 and os.path.exists(sys.argv[1]):
    v = json.load(open(sys.argv[1]))
    for key, pre in (("harness", "q38_fn_multiagent_p"), ("single", "q38_fn_single_p")):
        authors[key] = [v["q38-fn-5pass"][f"{pre}{k}"]["verdicts"] for k in range(1, 6)]
    authors["fable5"] = [v["fable5-128k-reasoning-on-5pass"][f"fable5_single_p{k}"]["verdicts"] for k in range(1, 6)]

def passes(key, pid): return sum(1 for vd in authors.get(key, []) if vd.get(pid))
W, left, top, rowh = 1000, 150, 110, 44
H = top + rowh * len(rows) + 150
cost_max = max(float(r["cost"].lstrip("$")) for r in rows)
out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" font-family="-apple-system, Helvetica, Arial, sans-serif" font-size="13">',
       f'<rect width="{W}" height="{H}" fill="#fff"/>',
       '<text x="20" y="34" font-size="20" font-weight="600">The ten: one prompt built the harness, one pass, Qwen3.8-27B</text>',
       '<text x="20" y="56" fill="#555">Memdoor stress harness (this run) beside the authors\' 27B harness and Claude Fable 5 alone (their five passes, same ids, their grader patched)</text>',
       f'<text x="{left}" y="{top-18}" fill="#555">problem</text>',
       f'<text x="{left+120}" y="{top-18}" fill="#555">ours: hidden tests · calls · cost (bar, ${cost_max:.2f} full)</text>',
       f'<text x="{left+560}" y="{top-18}" fill="#555">authors\' harness</text>',
       f'<text x="{left+700}" y="{top-18}" fill="#555">Fable 5 alone</text>']
solved = 0; total_cost = 0.0
for i, r in enumerate(rows):
    y = top + i * rowh; cost = float(r["cost"].lstrip("$")); total_cost += cost
    ok = r["solved"] == "yes"; solved += ok
    col = "#2e7d32" if ok else "#c62828"
    out.append(f'<text x="{left-130}" y="{y+5}" font-weight="600">{r["problem"]}</text>')
    out.append(f'<circle cx="{left+108}" cy="{y}" r="7" fill="{col}"/>')
    out.append(f'<rect x="{left+125}" y="{y-9}" width="{int(300*cost/cost_max)}" height="18" fill="{col}" opacity="0.25"/>')
    out.append(f'<text x="{left+130}" y="{y+5}">{r["hidden tests"]} · {r["calls"]} calls · ${cost:.2f}</text>')
    for key, x in (("harness", left+560), ("fable5", left+700)):
        if authors:
            p = passes(key, r["problem"])
            for k in range(5):
                out.append(f'<rect x="{x+k*18}" y="{y-7}" width="14" height="14" rx="2" fill="{"#2e7d32" if k < p else "#ddd"}"/>')
            out.append(f'<text x="{x+96}" y="{y+5}" fill="#555">{p}/5</text>')
y = top + len(rows) * rowh + 10
out.append(f'<line x1="20" y1="{y}" x2="{W-20}" y2="{y}" stroke="#ccc"/>')
stats = [f"ours: {solved} of {len(rows)} solved on all hidden tests, one pass, ${total_cost:.2f} including every failed attempt"]
if authors:
    for key, name in (("harness", "authors' 27B harness"), ("single", "authors' 27B single call"), ("fable5", "Fable 5 alone")):
        per_pass = [sum(1 for r in rows if vd.get(r["problem"])) for vd in authors[key]]
        stats.append(f"{name}: {min(per_pass)} to {max(per_pass)} of {len(rows)} by pass; on their hundred {min(sum(vd.values()) for vd in authors[key])} to {max(sum(vd.values()) for vd in authors[key])} (their patched grade)")
for j, s in enumerate(stats):
    out.append(f'<text x="20" y="{y+28+j*22}" fill="{"#000" if j == 0 else "#555"}">{s}</text>')
out.append(f'<text x="20" y="{H-16}" fill="#888" font-size="11">results/harness-stress-27b.tsv · bench/authors.py over the authors\' runs/patched_verdicts.json · generated by bench/chart.py</text>')
out.append("</svg>")
open(os.path.join(root, "results", "the-ten.svg"), "w").write("\n".join(out))
print("results/the-ten.svg", solved, "of", len(rows), f"${total_cost:.2f}")
